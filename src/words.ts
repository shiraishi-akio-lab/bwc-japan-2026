// 関心の出どころの種類。読んだページの場所と題から決める。分けられないものは「公開ページ」
export const sourceKind = (url: string, title: string) => {
  if (/\/(ir|investors?|kessan|financial)(\/|$)/i.test(url) || /決算/.test(title)) return "決算発表";
  if (/\/(news|press|release|releases|topics)(\/|$)/i.test(url) || /ニュース|リリース/.test(title)) return "ニュースリリース";
  if (/\/(torikumi|csr|sustainability|initiatives?)(\/|$)/i.test(url) || /取り組み/.test(title)) return "取り組み";
  return "公開ページ";
};
